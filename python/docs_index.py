"""fill the docs' generated index pages: below the marker, a table of the pages SUMMARY.md nests
under each one, by label, with the first sentence of each page's opening paragraph."""

import argparse
import posixpath
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parents[1] / "docs"
MARKER = "<!-- generated by python/docs_index.py -->"
ITEM = re.compile(r"^( *)- \[([^\]]+)\]\(([^)\s]+)\)")


def children(summary):
    """each page of ``summary``, SUMMARY.md's text, with the (label, page) of the items one level
    below it."""
    items = [(len(found[1]), found[2], found[3]) for found in map(ITEM.match, summary.splitlines()) if found]
    nested = {}
    for at, (indent, _, page) in enumerate(items):
        below = []
        for deeper, label, child in items[at + 1:]:
            if deeper <= indent:
                break
            if not below or deeper == below[0][0]:
                below.append((deeper, label, child))
        nested[page] = [(label, child) for _, label, child in below]
    return nested


def first_sentence(page):
    """the first sentence of the paragraph right below the H1 of ``page``'s text, its links as
    their text, or nothing when the page opens with something else."""
    lines = page.splitlines()
    start = next((at + 1 for at, line in enumerate(lines) if line.startswith("# ")), 0)
    paragraph = []
    for line in lines[start:]:
        if line.strip():
            paragraph.append(line.strip())
        elif paragraph:
            break
    text = " ".join(paragraph)
    if not text or re.match(r"#|`{3}|~{3}|\||<|[-*+] |\d+\. ", text):
        return ""
    text = re.sub(r"\[([^\]]*)\]\([^)\s]*\)", r"\1", text)
    # a full stop inside a code span, as in `data.toml`, ends nothing
    plain = re.sub(r"`[^`]*`", lambda span: "x" * len(span[0]), text)
    end = re.search(r"[.?!](\s|$)", plain)
    return text[:end.end()].strip() if end else text


def generate(docs):
    """{page: its text with the index below the marker} for each page of ``docs`` holding the
    marker on a line of its own."""
    pages = {}
    for page, below in children((docs / "SUMMARY.md").read_text(encoding="utf-8")).items():
        lines = (docs / page).read_text(encoding="utf-8").split("\n")
        if MARKER not in lines:
            continue
        rows = ["| Page | Summary |", "|---|---|"]
        for label, child in below:
            link = posixpath.relpath(child, posixpath.dirname(page) or ".")
            summary = first_sentence((docs / child).read_text(encoding="utf-8")).replace("|", "\\|")
            rows.append(f"| [{label}]({link}) | {summary} |" if summary else f"| [{label}]({link}) | |")
        pages[page] = "\n".join(lines[:lines.index(MARKER) + 1] + ["", *rows]) + "\n"
    return pages


def stale(docs):
    """the generated pages that differ from what ``generate`` makes of ``docs``."""
    return sorted(page for page, text in generate(docs).items()
                  if (docs / page).read_text(encoding="utf-8") != text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="only say which pages differ; exit 1 if any do")
    if parser.parse_args().check:
        found = stale(DOCS)
        for page in found:
            print(f"docs/{page} is not what python/docs_index.py writes")
        sys.exit(1 if found else 0)
    for page, text in generate(DOCS).items():
        (DOCS / page).write_text(text, encoding="utf-8")
        print(f"wrote docs/{page}")


if __name__ == "__main__":
    main()
